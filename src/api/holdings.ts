export function getLegacyFundHolding(code: string, holding: Omit<HoldingItem, 'remark'>[]) {
  const year = new Date().getFullYear() - 1;
  const target = funds.find((item) => item.code === code);
  if (!target) {
    return { year, stocks: [] };
  }

  const stocks = target[`year_${year}`];
  if (!stocks || stocks.length <= holding.length) {
    return { year, stocks: [] };
  }

  const rest = stocks.slice(holding.length - 1)
    .filter((item) => holding.every((stock) => stock.id !== item.id));

  return { year, stocks: rest };
}
